"""Corpus audit: extract + clean every manifest document, persist cleaned text, report quality."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from ragbench.config import repo_root
from ragbench.ingest.cleaning import clean_pages, quality_report
from ragbench.ingest.loaders import (
    RawPage,
    extract_pdf,
    extract_pypdf,
)
from ragbench.ingest.manifest import DocumentSpec, load_manifest


@dataclass
class DocAudit:
    spec: DocumentSpec
    extractor: str
    pages: int
    raw: dict[str, float | int]
    pypdf_raw: dict[str, float | int]
    clean: dict[str, float | int]
    refs_removed_chars: int
    boilerplate_removed_chars: int
    clean_pages: int
    sample: str


def _join(pages: list[RawPage]) -> str:
    return "\n".join(p.text for p in pages)


def audit_document(spec: DocumentSpec, corpus_dir: Path, processed_dir: Path) -> DocAudit:
    path = corpus_dir / spec.file
    raw_pages, extractor = extract_pdf(path)
    raw_text = _join(raw_pages)
    pypdf_text = _join(extract_pypdf(path))

    without_refs = clean_pages(raw_pages, None)
    cleaned = clean_pages(raw_pages, spec.references)
    text = "\n".join(p.text for p in cleaned)
    refs_removed = sum(len(p.text) for p in without_refs) - sum(len(p.text) for p in cleaned)

    processed_dir.mkdir(parents=True, exist_ok=True)
    out = {
        "doc_id": spec.id,
        "title": spec.title,
        "role": spec.role,
        "source_file": spec.file,
        "extractor": extractor,
        "pages": [{"page": p.number, "text": p.text} for p in cleaned],
    }
    (processed_dir / f"{spec.id}.json").write_text(
        json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8"
    )
    return DocAudit(
        spec=spec,
        extractor=extractor,
        pages=len(raw_pages),
        raw=quality_report(raw_text),
        pypdf_raw=quality_report(pypdf_text),
        clean=quality_report(text),
        refs_removed_chars=refs_removed,
        boilerplate_removed_chars=len(raw_text) - sum(len(p.text) for p in without_refs),
        clean_pages=len(cleaned),
        sample=re.sub(r"\s+", " ", text[1500:1800]),
    )


def run_audit(root: Path | None = None) -> str:
    root = root or repo_root()
    manifest = load_manifest(root / "data" / "corpus" / "manifest.yaml")
    corpus_dir = root / "data" / "corpus"
    processed_dir = root / "data" / "processed"
    audits = [audit_document(s, corpus_dir, processed_dir) for s in manifest.documents]

    lines = [
        "# Corpus audit",
        "",
        "Generated by `ragbench audit` (Phase 0). Do not edit by hand.",
        "",
    ]
    lines += [
        "## Indexed documents",
        "",
        "| id | role | pages | extractor | raw chars | cleaned chars | refs cut | "
        "PUA (pypdf -> chosen) | spaced-letter runs | line-end hyphens left |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for a in audits:
        lines.append(
            f"| {a.spec.id} | {a.spec.role} | {a.pages} | {a.extractor} | {a.raw['chars']} | "
            f"{a.clean['chars']} | {a.refs_removed_chars} | "
            f"{a.pypdf_raw['pua_chars']} -> {a.clean['pua_chars']} | "
            f"{a.clean['spaced_letter_runs']} | {a.clean['line_end_hyphens']} |"
        )
    lines += ["", "## Cleaned text samples (chars 1500-1800)", ""]
    for a in audits:
        lines += [f"**{a.spec.id}**", "", f"> {a.sample}", ""]

    report = "\n".join(lines) + "\n"
    (root / "docs" / "corpus_audit.md").write_text(report, encoding="utf-8")
    return report
